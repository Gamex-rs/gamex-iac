#!/bin/bash
# Creates .env for local development with a fresh RS256 key pair (User Library signs, other services verify).
# Keys are written as single lines with "\n" escapes, which all services accept.
set -euo pipefail
cd "$(dirname "$0")/.."

if [ -f .env ] && [ "${1:-}" != "--force" ]; then
  echo ".env already exists (use --force to overwrite)." >&2
  exit 1
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "$tmp/private.pem" 2>/dev/null
openssl pkey -in "$tmp/private.pem" -pubout -out "$tmp/public.pem"

# Joins PEM lines with a literal backslash-n (two characters), so each key fits on one .env line.
oneline() { awk 'BEGIN { ORS = "\\n" } { print }' "$1"; }

cat > .env <<ENV
# Generated by scripts/generate-dev-env.sh — local development only, never commit.
JWT_PRIVATE_KEY=$(oneline "$tmp/private.pem")
JWT_PUBLIC_KEY=$(oneline "$tmp/public.pem")
RAWG_API_KEY=
GOOGLE_CLIENT_ID=
GOOGLE_CLIENT_SECRET=
FACEBOOK_APP_ID=
FACEBOOK_APP_SECRET=
ENV

echo "Wrote .env with a new dev key pair."
